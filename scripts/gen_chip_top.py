#!/usr/bin/env python3
"""Generate src/chip_top.v and librelane/pads.yaml for the GF180MCU pad ring.

Pad ring: 22 pads per side (88 total), 2987 um square die, 100 um pad pitch.
Pins are numbered counter-clockwise from the top-left corner:
  West  (top->bottom) : posit_PAD[31:16]
  South (left->right) : posit_PAD[15:0]
  East  (bottom->top) : output bits 0..18
  North (right->left) : output bits 19..37
Output bit order: {sign, reg[5:0], exp[1:0], inf, mant[27:0]} = out[37:0].
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUT_BITS = ([f"mant{i:02d}" for i in range(28)] + ["inf"] + ["exp0", "exp1"]
            + [f"reg{i}" for i in range(6)] + ["sign"])
OUT_PORT = {**{f"mant{i:02d}": f"mant_PAD[{i}]" for i in range(28)},
            "inf": "inf_PAD", "exp0": "exp_PAD[0]", "exp1": "exp_PAD[1]",
            **{f"reg{i}": f"reg_PAD[{i}]" for i in range(6)}, "sign": "sign_PAD"}


def inp(i):
    return f"pad_in{i:02d}"


def outp(i):
    return f"pad_{OUT_BITS[i]}"


power = {"dvdd": [], "dvss": []}


def pwr(kind):
    name = f"pad_{kind}{len(power[kind])}"
    power[kind].append(name)
    return name


def VP():  # one DVDD + one DVSS pair
    return [pwr("dvdd"), pwr("dvss")]


# Lists are in increasing coordinate order (south/north: x, east/west: y).
west = VP() + [inp(i) for i in range(16, 24)] + VP() + [inp(i) for i in range(24, 32)] + VP()
south = VP() + [inp(i) for i in range(15, 7, -1)] + VP() + [inp(i) for i in range(7, -1, -1)] + VP()
east = [pwr("dvss")] + [outp(i) for i in range(0, 10)] + [pwr("dvdd")] + [outp(i) for i in range(10, 19)] + [pwr("dvss")]
north = [pwr("dvdd")] + [outp(i) for i in range(37, 27, -1)] + [pwr("dvss")] + [outp(i) for i in range(27, 18, -1)] + [pwr("dvdd")]

for side in (west, south, east, north):
    assert len(side) == 22, len(side)
assert sorted(p for s in (west, south) for p in s if p.startswith("pad_in")) == sorted(inp(i) for i in range(32))
assert sorted(p for s in (east, north) for p in s if p.startswith("pad_") and not p.startswith(("pad_dv",))) \
    == sorted(outp(i) for i in range(38))

PW = """`ifdef USE_POWER_PINS
        .DVDD (DVDD), .DVSS (DVSS), .VDD (VDD), .VSS (VSS),
`endif"""
PW_ONLY = """`ifdef USE_POWER_PINS
        .DVDD (DVDD), .DVSS (DVSS), .VDD (VDD), .VSS (VSS)
`endif"""

v = ["// Generated by scripts/gen_chip_top.py -- do not edit by hand.",
     "// GF180MCU chip top: posit<32,2> decoder inside an 88-pad ring.",
     "`default_nettype none", "",
     "module chip_top (",
     "`ifdef USE_POWER_PINS",
     "    inout  wire VDD,", "    inout  wire VSS,", "    inout  wire DVDD,", "    inout  wire DVSS,",
     "`endif",
     "    inout  wire [31:0] posit_PAD,",
     "    inout  wire        sign_PAD,",
     "    inout  wire [5:0]  reg_PAD,",
     "    inout  wire [1:0]  exp_PAD,",
     "    inout  wire        inf_PAD,",
     "    inout  wire [27:0] mant_PAD",
     ");", "",
     "    wire [31:0] core_in;", "    wire [37:0] core_out;", "",
     "    // gf180mcu_fd_io shorts the I/O and core supply domains",
     "`ifdef USE_POWER_PINS", "    assign VDD = DVDD;", "    assign VSS = DVSS;", "`endif", ""]

v.append("    // ---------------- Supply pads ----------------")
for kind in ("dvdd", "dvss"):
    for name in power[kind]:
        v += [f"    (* keep *) gf180mcu_fd_io__{kind} {name} (", PW_ONLY, "    );"]
v.append("")
v.append("    // ---------------- Input pads ----------------")
for i in range(32):
    v += [f"    (* keep *) gf180mcu_fd_io__in_c {inp(i)} (", PW,
          f"        .PAD (posit_PAD[{i}]), .Y (core_in[{i}]), .PU (1'b0), .PD (1'b0)", "    );"]
v.append("")
v.append("    // ---------------- Output pads (bidirectional cell, output mode) ----------------")
for i in range(38):
    v += [f"    (* keep *) gf180mcu_fd_io__bi_24t {outp(i)} (", PW,
          f"        .PAD ({OUT_PORT[OUT_BITS[i]]}), .A (core_out[{i}]), .OE (1'b1), .Y (),",
          "        .CS (1'b0), .SL (1'b0), .IE (1'b0), .PU (1'b0), .PD (1'b0)", "    );"]
v += ["",
      "    // ---------------- Core ----------------",
      "    posit_decoder_32_2 u_core (",
      "        .posit_in (core_in),",
      "        .S        (core_out[37]),",
      "        .reg_O    (core_out[36:31]),",
      "        .EXP_O    (core_out[30:29]),",
      "        .inf      (core_out[28]),",
      "        .Mantissa (core_out[27:0])",
      "    );", "",
      "    // ---------------- Die art (corner badges) ----------------",
      "    (* keep *) dieart_tl art_tl ();",
      "    (* keep *) dieart_tr art_tr ();",
      "    (* keep *) dieart_bl art_bl ();",
      "    (* keep *) dieart_br art_br ();", "",
      "endmodule", "", "`default_nettype wire", ""]

with open(os.path.join(ROOT, "src", "chip_top.v"), "w") as f:
    f.write("\n".join(v))


def ylist(name, items):
    return f"{name}:\n" + "".join(f"  - {it}\n" for it in items)


with open(os.path.join(ROOT, "librelane", "pads.yaml"), "w") as f:
    f.write("# Generated by scripts/gen_chip_top.py -- do not edit by hand.\n")
    f.write("# Lists run in increasing coordinate order along each side.\n")
    for name, side in (("PAD_SOUTH", south), ("PAD_EAST", east), ("PAD_NORTH", north), ("PAD_WEST", west)):
        f.write(ylist(name, side))

print(f"DVDD pads: {len(power['dvdd'])}, DVSS pads: {len(power['dvss'])}, signal pads: 70")

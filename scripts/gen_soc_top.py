#!/usr/bin/env python3
"""Generate src/soc/soc_chip_top.v and librelane/soc/pads.yaml (40-pad ring).

10 pads per side, 2392 um die, 155 um pitch. Signal pads sit at both ends of
each side; the supply pads (6 DVDD + 6 DVSS) sit inward.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name -> (pad kind, port expression)
#   in_s / in_c : input pad, Y -> core signal
#   out         : bi_24t, output only
#   bidir       : bi_24t with output enable
SIG = {"clk": ("in_s", "clk_PAD"), "rst_n": ("in_c", "rst_n_PAD"),
       "ser_rx": ("in_c", "ser_rx_PAD"), "irq5": ("in_c", "irq5_PAD"), "irq6": ("in_c", "irq6_PAD"),
       "ser_tx": ("out", "ser_tx_PAD"), "flash_csb": ("out", "flash_csb_PAD"),
       "flash_clk": ("out", "flash_clk_PAD")}
for i in range(4):
    SIG[f"flash_io{i}"] = ("bidir", f"flash_io_PAD[{i}]")
for i in range(16):
    SIG[f"gpio{i:02d}"] = ("bidir", f"gpio_PAD[{i}]")

power = {"dvdd": [], "dvss": []}


def P(kind):
    name = f"pad_{kind}{len(power[kind])}"
    power[kind].append(name)
    return name


def side(sigs, kinds):
    s = [f"pad_{x}" for x in sigs]
    return s[0:2] + [P(kinds[0])] + s[2:4] + [P(kinds[1])] + s[4:6] + [P(kinds[2])] + s[6:7]


A, B = ("dvdd", "dvss", "dvdd"), ("dvss", "dvdd", "dvss")
west = side([f"gpio{i:02d}" for i in range(0, 7)], A)
north = side([f"gpio{i:02d}" for i in range(7, 14)], B)
east = side(["gpio14", "gpio15", "irq5", "irq6", "ser_rx", "ser_tx", "rst_n"], A)
south = side(["clk", "flash_csb", "flash_clk", "flash_io0", "flash_io1", "flash_io2", "flash_io3"], B)
for s in (west, north, east, south):
    assert len(s) == 10
assert len(power["dvdd"]) == 6 and len(power["dvss"]) == 6

PW = "`ifdef USE_POWER_PINS\n        .DVDD (DVDD), .DVSS (DVSS), .VDD (VDD), .VSS (VSS),\n`endif"
PWO = "`ifdef USE_POWER_PINS\n        .DVDD (DVDD), .DVSS (DVSS), .VDD (VDD), .VSS (VSS)\n`endif"

v = ["// Generated by scripts/gen_soc_top.py -- do not edit by hand.",
     "// GF180MCU chip top: RISC-V SoC with posit<32,2> accelerator, 40-pad ring.",
     "`default_nettype none", "",
     "module soc_chip_top (",
     "`ifdef USE_POWER_PINS",
     "    inout  wire VDD,", "    inout  wire VSS,", "    inout  wire DVDD,", "    inout  wire DVSS,",
     "`endif",
     "    inout  wire clk_PAD,", "    inout  wire rst_n_PAD,",
     "    inout  wire ser_tx_PAD,", "    inout  wire ser_rx_PAD,",
     "    inout  wire irq5_PAD,", "    inout  wire irq6_PAD,",
     "    inout  wire flash_csb_PAD,", "    inout  wire flash_clk_PAD,",
     "    inout  wire [3:0]  flash_io_PAD,",
     "    inout  wire [15:0] gpio_PAD",
     ");", "",
     "`ifdef USE_POWER_PINS", "    assign VDD = DVDD;  // gf180mcu_fd_io shorts the domains", "    assign VSS = DVSS;", "`endif", "",
     "    wire clk, rst_n, ser_rx, irq5, irq6, ser_tx, flash_csb, flash_clk;",
     "    wire [3:0]  flash_io_oe, flash_io_do, flash_io_di;",
     "    wire [15:0] gpio_out, gpio_oe, gpio_in;", ""]


def core_sig(name):
    if name.startswith("flash_io"):
        i = int(name[-1])
        return f"flash_io_do[{i}]", f"flash_io_oe[{i}]", f"flash_io_di[{i}]"
    if name.startswith("gpio"):
        i = int(name[4:])
        return f"gpio_out[{i}]", f"gpio_oe[{i}]", f"gpio_in[{i}]"
    return name, None, None


v.append("    // Supply pads")
for kind in ("dvdd", "dvss"):
    for n in power[kind]:
        v += [f"    (* keep *) gf180mcu_fd_io__{kind} {n} (", PWO, "    );"]
v.append("")
v.append("    // Signal pads")
for name, (kind, port) in SIG.items():
    inst = f"pad_{name}"
    if kind in ("in_s", "in_c"):
        v += [f"    (* keep *) gf180mcu_fd_io__{kind} {inst} (", PW,
              f"        .PAD ({port}), .Y ({name}), .PU (1'b0), .PD (1'b0)", "    );"]
    elif kind == "out":
        v += [f"    (* keep *) gf180mcu_fd_io__bi_24t {inst} (", PW,
              f"        .PAD ({port}), .A ({name}), .OE (1'b1), .Y (),",
              "        .CS (1'b0), .SL (1'b0), .IE (1'b0), .PU (1'b0), .PD (1'b0)", "    );"]
    else:
        do, oe, di = core_sig(name)
        v += [f"    (* keep *) gf180mcu_fd_io__bi_24t {inst} (", PW,
              f"        .PAD ({port}), .A ({do}), .OE ({oe}), .Y ({di}),",
              f"        .CS (1'b0), .SL (1'b0), .IE (~{oe}), .PU (1'b0), .PD (1'b0)", "    );"]
v += ["",
      "    soc_top u_soc (",
      "`ifdef USE_POWER_PINS", "        .VDD (VDD), .VSS (VSS),", "`endif",
      "        .clk (clk), .resetn (rst_n),",
      "        .ser_tx (ser_tx), .ser_rx (ser_rx), .irq_5 (irq5), .irq_6 (irq6),",
      "        .flash_csb (flash_csb), .flash_clk (flash_clk),",
      "        .flash_io_oe (flash_io_oe), .flash_io_do (flash_io_do), .flash_io_di (flash_io_di),",
      "        .gpio_out (gpio_out), .gpio_oe (gpio_oe), .gpio_in (gpio_in)",
      "    );", "",
      "    (* keep *) dieart_tl art_tl ();",
      "    (* keep *) dieart_tr art_tr ();",
      "    (* keep *) dieart_bl art_bl ();",
      "    (* keep *) dieart_br art_br ();", "",
      "endmodule", "", "`default_nettype wire", ""]

os.makedirs(os.path.join(ROOT, "librelane", "soc"), exist_ok=True)
with open(os.path.join(ROOT, "src", "soc", "soc_chip_top.v"), "w") as f:
    f.write("\n".join(v))
with open(os.path.join(ROOT, "librelane", "soc", "pads.yaml"), "w") as f:
    f.write("# Generated by scripts/gen_soc_top.py -- do not edit by hand.\n")
    for n, s in (("PAD_SOUTH", south), ("PAD_EAST", east), ("PAD_NORTH", north), ("PAD_WEST", west)):
        f.write(f"{n}:\n" + "".join(f"  - {x}\n" for x in s))
print("W", west); print("N", north); print("E", east); print("S", south)

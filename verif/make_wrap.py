#!/usr/bin/env python3
"""Write a wrapper around the GHDL netlist with the Verilog RTL port names.

GHDL may keep or fold the case of VHDL identifiers depending on its version,
so the wrapper reads the actual module and port names from the netlist.
Usage: make_wrap.py <gold_ghdl.v> <out_wrapper.v>
"""
import re
import sys

PORT_MAP = {"input": "posit_in", "s": "S", "reg_o": "reg_O", "exp_o": "EXP_O",
            "inf": "inf", "mantissa": "Mantissa"}

src = open(sys.argv[1]).read()
m = re.search(r"module\s+(\\\S+\s|[A-Za-z_][\w$]*)\s*\((.*?)\);", src, re.S)
if not m:
    sys.exit("no module header found")
module = m.group(1).strip()
ports = [p.strip() for p in m.group(2).split(",") if p.strip()]


def plain(name):
    return name[1:].strip() if name.startswith("\\") else name


conn = []
for p in ports:
    key = plain(p).lower()
    if key not in PORT_MAP:
        sys.exit(f"unexpected port {p}")
    ref = p + " " if p.startswith("\\") else p
    conn.append(f"        .{ref}({PORT_MAP[key]})")
mod_ref = module + " " if module.startswith("\\") else module

with open(sys.argv[2], "w") as f:
    f.write(f"""// Generated by verif/make_wrap.py from the GHDL netlist.
module gold_wrap (
    input  wire [31:0] posit_in,
    output wire        S,
    output wire [5:0]  reg_O,
    output wire [1:0]  EXP_O,
    output wire        inf,
    output wire [27:0] Mantissa
);
    {mod_ref} u_gold (
{(","+chr(10)).join(conn)}
    );
endmodule
""")
print(f"wrapper for module {module} with ports {[plain(p) for p in ports]}")

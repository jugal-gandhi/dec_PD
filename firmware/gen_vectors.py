#!/usr/bin/env python3
"""Generate firmware/vectors.h: posit<32,2> inputs and expected decoder outputs.

The model mirrors src/posit_decoder_32_2.v bit for bit (which is formally
proven equivalent to Decoder_32_2.vhd). Register layout as in soc_top.v:
  POSIT_FLD  = {inf, sign, exp[1:0], reg[5:0]}
  POSIT_MANT = mantissa[27:0]
"""
import random
import sys

M30 = (1 << 30) - 1


def decode(x):
    sign = (x >> 31) & 1
    rc = (x >> 30) & 1
    d = x & M30
    counts = []
    for hi, lo, sh in ((29, 14, 16), (29, 21, 8), (29, 25, 4), (29, 27, 2), (29, 29, 1)):
        win = (d >> lo) & ((1 << (hi - lo + 1)) - 1)
        full = (1 << (hi - lo + 1)) - 1
        d_and = (1 if win == full else 0) if rc else (1 if win else 0)
        if (hi, lo) == (29, 29):
            d_and = (d >> 29) & 1
        c = 1 if d_and == rc else 0
        counts.append(c)
        if c:
            d = (d << sh) & M30
    c4, c3, c2, c1, c0 = counts
    k = (c4 << 4) | (c3 << 3) | (c2 << 2) | (c1 << 1) | c0
    zero_check = sign if c4 else 1
    inf = 1 if (zero_check == 0 and sign == 1) else 0
    reg = ((1 << 5) | (~k & 31)) if rc == sign else k
    exp = (d >> 27) & 3
    mant = (zero_check << 27) | (d & ((1 << 27) - 1))
    return (inf << 9) | (sign << 8) | (exp << 6) | reg, mant


def main():
    rng = random.Random(2026)
    vec = [0x00000000, 0x80000000, 0x40000000, 0x7FFFFFFF, 0xFFFFFFFF, 0x3FFFFFFF,
           0x48000000, 0x12345678, 0xC0FFEE00, 0x00000001]
    for run in range(0, 31, 3):
        for rc in (0, 1):
            tail = rng.getrandbits(30)
            body = (~(M30 >> run) & M30) if rc else (M30 >> run)
            body ^= tail & (M30 >> (run + 1))
            vec.append((rng.getrandbits(1) << 31) | (rc << 30) | body)
    vec += [rng.getrandbits(32) for _ in range(20)]
    out = sys.argv[1] if len(sys.argv) > 1 else "firmware/vectors.h"
    with open(out, "w") as f:
        f.write("// Generated by firmware/gen_vectors.py\n#include <stdint.h>\n")
        f.write(f"#define NVEC {len(vec)}\n")
        f.write("static const uint32_t vectors[NVEC][3] = {\n")
        for x in vec:
            fld, mant = decode(x)
            f.write(f"    {{0x{x:08x}u, 0x{fld:08x}u, 0x{mant:08x}u}},\n")
        f.write("};\n")
    print(f"{len(vec)} vectors -> {out}")


if __name__ == "__main__":
    main()
